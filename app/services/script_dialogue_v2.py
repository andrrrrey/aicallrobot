def _is_bare_number_echo(lower: str) -> bool:
    """Реплика — это голое «номер телефона» / «какой номер», без цифр и без «ваш/наш»."""
    if any(ch.isdigit() for ch in lower):
        return False
    words = re.findall(r"[а-яё]+", lower)
