def _is_hold_request(lower: str) -> bool:
    """Реплика — это перебивание/просьба остановиться без иного смысла.

    «Татьяна, Татьяна», «стойте стойте», «остановитесь», «минутку» → True.
    «Подождите, я не соединяю», «секунду, сейчас позову» → False (есть иной смысл).
    """
    if any(p in lower for p in WAIT_SIGNALS):
        return True
    if any(p in lower for p in _LISTEN_PHRASES):
        return True
    words = re.findall(r"[а-яё]+", lower)
    if not any(any(w.startswith(s) for s in _ATTENTION_STEMS) for w in words):
        return False
    residual = [
        w for w in words
        if not any(w.startswith(s) for s in _ATTENTION_STEMS) and w not in _HOLD_FILLER
    ]
    return not residual


