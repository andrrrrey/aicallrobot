def _format_history(exchanges: list) -> str:
    """Форматирует список обменов в читаемый текст для промпта."""
    if not exchanges:
        return "(начало разговора)"
    parts = []
    for e in exchanges:
        role = "Робот" if e["role"] == "robot" else "Собеседник"
        parts.append(f"{role}: {e['text']}")
    return "\n".join(parts)


class ScriptDialogueV2:
    """Скриптовый движок диалога v2: классификация через ИИ, ответы из скрипта."""

    MAX_SESSIONS = 500

    def __init__(self, gpt_service: YandexGPTService, corrections=None):
        self.gpt = gpt_service
        self._corrections = corrections  # ScriptCorrectionsService | None
        self._sessions: dict[str, V2SessionState] = {}

    # ── Управление сессиями ────────────────────────────────────────────────────

    def create_session(self, session_id: str) -> V2SessionState:
        if len(self._sessions) >= self.MAX_SESSIONS:
            oldest = min(self._sessions.values(), key=lambda s: s.created_at)
            del self._sessions[oldest.session_id]
        state = V2SessionState(session_id=session_id)
        self._sessions[session_id] = state
        return state

    def get_session(self, session_id: str) -> V2SessionState | None:
        return self._sessions.get(session_id)

    def delete_session(self, session_id: str) -> None:
        self._sessions.pop(session_id, None)

    def greeting(self, session_id: str, company_name: str = "") -> dict:
        """Первая реплика робота — короткое «Алло» (фаза рукопожатия).

        Скрипт продаж запускается только после того, как ответит живой человек
        (см. ``_handle_answer_check``). ``company_name`` — название компании из
        базы клиентов, используется для уточнения «Это компания N?».
        """
        state = self.get_session(session_id)
        if not state:
            state = self.create_session(session_id)
        if company_name:
            state.company_name = company_name.strip()
        state.phase = "handshake"
        text = SCRIPT["handshake_hello"]
        state.last_robot_text = text
        return self._response(text, "handshake", "handshake_hello", state)

    def set_company_name(self, session_id: str, company_name: str) -> None:
        """Проставляет название компании из базы клиентов (для рукопожатия)."""
        state = self.get_session(session_id) or self.create_session(session_id)
        state.company_name = (company_name or "").strip()

    # ── Основной метод обработки реплики ──────────────────────────────────────

    async def process_turn(self, session_id: str, user_text: str) -> dict:
        """Обрабатывает одну реплику пользователя, возвращает ответ из скрипта."""
        state = self.get_session(session_id)
        if not state:
            state = self.create_session(session_id)

        user_text = user_text.strip()
        if not user_text:
            # В фазе рукопожатия тишина/нераспознанное — повод уточнить, человек ли
            # на линии (а не запускать скрипт как при обычном пустом ответе).
            if state.phase == "handshake":
                robot_text, node = self._handle_answer_check(state, "")
                state.last_robot_text = robot_text
                return self._response(robot_text, state.phase, node, state)
            return self._response(SCRIPT["fallback_secretary"], state.phase, "empty", state)

        if state.phase == "closed":
            return self._response(SCRIPT["closed"], "closed", "closed", state)

        # Считаем, сколько раз подряд прозвучал один и тот же ответ (антидолбёжка)
        normalized = _normalized_answer(user_text)
        if normalized and normalized == state.last_user_text:
            state.same_answer_streak += 1
        else:
            state.same_answer_streak = 1
        state.last_user_text = normalized

        phase_before = state.phase
        robot_text, node = await self._dispatch(state, user_text)

        # Слой коррекции ответов: если реплика похожа на пример из таблицы правок,
        # произносим «правильный» ответ из правки вместо ответа скрипта.
        # Логика фаз/переходов не меняется — подменяется только текст.
        #
        # В фазе рукопожатия правки НЕ применяются: там ещё не прозвучало ни
        # приветствие, ни вопрос, и любое ложное срабатывание выглядит дико —
        # именно так робот начинал разговор с диктовки нашего же номера в ответ
        # на «здравствуйте, вы позвонили в …».
        #
        # Фазу берём ДО обработки (``phase_before``): правка описывает ситуацию,
        # в которой собеседник произнёс фразу, а не ту, куда диалог успел уйти.
        # Правки НЕ применяем, когда:
        #  * робот сейчас МОЛЧА пишет номер (node recording_number / пустой текст,
        #    await_answer) — подменять молчание правкой нельзя;
        #  * собеседник диктует свой номер — иначе правка может «в ответ»
        #    продиктовать НАШ номер поверх записи чужого.
        _skip_correction = (
            not robot_text
            or node in ("recording_number", "await_answer", "await_their_number")
            or state.secretary_collecting_number
            or _is_dictating_number(user_text)
        )
        if (self._corrections is not None
                and phase_before not in ("handshake", "closed")
                and not _skip_correction):
            override = await self._corrections.match(user_text, phase_before)
            if override:
                logger.info(f"[v2-correction] session={session_id} node={node} → correction")
                robot_text, node = override, "correction"

        # Не распознали намерение: пишем эпизод в отладочный лог и отвечаем
        # по лестнице эскалации (переспрос → уточнение → оставить контакты).
        # РАНЬШЕ здесь звучала отладочная заглушка «Я затрудняюсь ответить на
        # ваш вопрос» — она подменяла собой все штатные фоллбэки скрипта и
        # могла повторяться бесконечно.
        if node in _DEBUG_UNKNOWN_NODES:
            state.total_unknown_count += 1
            state.unknown_streak += 1
            self._save_unknown_debug(state, user_text, node)
            robot_text, node = self._unknown_response(state)
        else:
            state.unknown_streak = 0

        # Детекция зацикливания: тот же ответ дважды подряд
        if robot_text == state.last_robot_text and node not in _NO_LOOP_NODES:
            state.loop_streak += 1
            logger.warning(
                f"[v2-loop] streak={state.loop_streak} node={node} "
                f"session={session_id} text='{user_text[:60]}'"
            )
            recovery = await self._recover_from_loop(state, user_text, node)
            if recovery:
                robot_text, node = recovery
                logger.info(f"[v2-loop] recovered → node={node}")
            else:
                # Выхода из петли ИИ не нашёл — идём по той же лестнице, что и
                # при нераспознанной реплике (переспрос → уточнение → закрытие),
                # вместо повторения одной и той же фразы.
                state.unknown_streak += 1
                robot_text, node = self._unknown_response(state)
                logger.info(f"[v2-loop] no recovery found → {node}")
            state.loop_streak = 0
        else:
            state.loop_streak = 0

        # Антиповтор: не задаём один и тот же вопрос двумя репликами подряд
        robot_text = self._avoid_repeat_question(
            state, robot_text, node, state.phase != phase_before,
        )

        # Собираем данные и результат звонка (телефон, имя, сроки, исход)
        self._track_turn(state, user_text, node, robot_text)

        # Молчание (разговор собеседника «в сторону») контекст не сбрасывает:
        # последняя реплика робота остаётся прежней — на неё завязаны проверки
        # контекста в фазах ЛПР и распознавание просьбы повторить.
        if robot_text:
            state.last_robot_text = robot_text

        # Обновляем историю диалога (последние 10 сообщений = 5 обменов)
        state.recent_exchanges.append({"role": "user", "text": user_text, "intent": node})
        if robot_text:
            state.recent_exchanges.append({"role": "robot", "text": robot_text})
        if len(state.recent_exchanges) > 10:
            state.recent_exchanges = state.recent_exchanges[-10:]

        # Трекаем сопротивление секретаря для контекста классификации
        if node in _NEGATIVE_NODES and state.phase == "secretary":
            state.negative_turn_count += 1

        logger.info(
            f"[v2] session={session_id} phase={state.phase} node={node} "
            f"neg={state.negative_turn_count} loop={state.loop_streak} "
            f"text='{user_text[:60]}' → '{robot_text[:60]}'"
        )
        return self._response(robot_text, state.phase, node, state)

    # ── Диспетчер по фазам ────────────────────────────────────────────────────

    async def _dispatch(self, state: V2SessionState, user_text: str) -> tuple[str, str]:
        lower = user_text.lower()

        # Собеседник прощается / кладёт трубку — завершаем диалог.
        # Проверяется ПЕРВЫМ: даже если в реплике есть «остановитесь/передам»,
        # явное «до свидания» означает намерение завершить разговор.
        if _is_goodbye(lower):
            state.phase = "closed"
            return SCRIPT["farewell"], "farewell"

        # Фаза рукопожатия: проверяем, что трубку взял живой человек, а не IVR /
        # автоответчик. Скрипт запускаем только после человеческого отклика.
        if state.phase == "handshake":
            return self._handle_answer_check(state, user_text)

        # Собеседник говорит не с нами, а с коллегой рядом («Дим Фёдорович, бот
        # спрашивает…», «Сейчас позову») — молчим и ждём. Отвечать скриптом на
        # чужой разговор нельзя: именно так робот выглядит сломанным.
        if _is_side_talk(lower):
            state.awaiting_new_person = True
            return "", "side_talk"

        # Трубку передали другому человеку: после «сейчас позову»/«подождите»
        # короткий отклик-приветствие принадлежит уже НОВОМУ собеседнику —
        # коротко представляемся заново, а не продолжаем прошлый разговор.
        if state.awaiting_new_person and _is_pickup_greeting(lower):
            state.awaiting_new_person = False
            state.phase = "lpr_greeting"
            state.lpr_greeted = True
            return SCRIPT["handoff_hello"], "handoff_hello"

        # Собеседник просит повторить (не расслышал / не записал) — повторяем
        # прошлую реплику робота, а не идём по сценарию дальше.
        if state.last_robot_text and _is_repeat_request(lower):
            return state.last_robot_text, "repeat"

        # Перебивание / просьба остановиться («Татьяна, Татьяна», «стойте стойте»,
        # «остановитесь», «минутку») — короткое «Да, я вас слушаю» без перевода
        # звонка и без рестарта диалога. Часто за этим идут звать ответственного.
        if _is_hold_request(lower):
            state.awaiting_new_person = True
            return SCRIPT["hold_on"], "hold_on"

        # Третий подряд «никто» / «не знаю»: перебирать формулировки дальше
        # бессмысленно — вежливо закрываем разговор, а не ходим по кругу.
        if (state.phase == "secretary"
                and state.same_answer_streak >= _STONEWALL_LIMIT
                and _normalized_answer(user_text) in _STONEWALL_ANSWERS):
            logger.info(
                f"[v2] {state.same_answer_streak}-й одинаковый ответ "
                f"'{user_text[:30]}' — закрываем разговор"
            )
            state.phase = "closed"
            return SCRIPT["secretary_stonewall_close"], "stonewall_close"

        # Содержательная реплика — значит, трубку никому не передавали.
        state.awaiting_new_person = False

        if state.phase == "secretary":
            return await self._handle_secretary(state, user_text)
        elif state.phase == "lpr_greeting":
            return await self._handle_lpr_greeting(state, user_text)
        elif state.phase == "lpr_main":
            return await self._handle_lpr_main(state, user_text)
        elif state.phase == "qualification":
            return await self._handle_qualification(state, user_text)
        return SCRIPT["fallback_secretary"], "unknown"

    # ── Фаза: Рукопожатие (живой человек vs IVR/автоответчик) ──────────────────

    def _handle_answer_check(self, state: V2SessionState, user_text: str) -> tuple[str, str]:
        """Определяет, ответил ли живой человек, и решает, запускать ли скрипт.

        - Человеческий отклик («алло», «да», «слушаю», «компания N») → скрипт.
        - IVR / автоответчик («нажмите 1», «оставьте сообщение») → кладём трубку.
        - Неясно (тишина, шум) → уточняем «Это компания N?» / «Вы меня слышите?»;
          если и после уточнения непонятно — завершаем звонок.
        """
        lower = user_text.lower()
        human = _matches_signal(lower, HUMAN_ANSWER_SIGNALS)

        # Жёсткие маркеры автоответчика («оставьте сообщение после сигнала») —
        # человек так не отвечает, кладём трубку.
        if any(sig in lower for sig in MACHINE_SIGNALS_HARD):
            state.phase = "closed"
            return "", "answering_machine"

        # Голосовое меню («…по вопросам аренды нажмите цифру два…»). Скрипт
        # запускать рано — иначе робот выкладывает приветствие автоинформатору,
        # а подошедший следом живой человек слышит уже середину разговора и не
        # понимает, кто звонит. Молчим и ждём человека; если меню тянется —
        # кладём трубку.
        if _is_ivr_menu(lower):
            state.ivr_waits += 1
            if state.ivr_waits <= _IVR_WAIT_LIMIT:
                logger.info(
                    f"[v2] голосовое меню ({state.ivr_waits}/{_IVR_WAIT_LIMIT}) — "
                    f"молчим и ждём живого человека"
                )
                return "", "ivr_wait"
            state.phase = "closed"
            return "", "answering_machine"

        # Мягкие маркеры («наберите добавочный», «вы позвонили в компанию N»)
        # встречаются и у живого секретаря. Считаем автоответчиком, только если
        # признаков живого ответа в реплике нет.
        if not human and any(sig in lower for sig in MACHINE_SIGNALS_SOFT):
            state.phase = "closed"
            return "", "answering_machine"

        # Человеческий отклик → запускаем скрипт продаж (приветствие секретаря).
        if human:
            return self._begin_script(state)

        # Неясный ответ (тишина, обрывок, шум).
        if not state.handshake_clarify_asked:
            state.handshake_clarify_asked = True
            if state.company_name:
                return (
                    f"Извините, я вас плохо слышу. Это компания «{state.company_name}»?",
                    "handshake_clarify",
                )
            return SCRIPT["handshake_clarify"], "handshake_clarify"

        # Уже уточняли, но так и не поняли, что на линии человек — кладём трубку.
        state.phase = "closed"
        return "", "no_human"

    def _begin_script(self, state: V2SessionState) -> tuple[str, str]:
        """Живой человек подтверждён — переходим к скрипту продаж (фаза секретаря)."""
        state.phase = "secretary"
        state.secretary_greeted = True
        return SCRIPT["greeting"], "greeting"

    # ── Фаза: Секретарь ───────────────────────────────────────────────────────

    async def _handle_secretary(self, state: V2SessionState, user_text: str) -> tuple[str, str]:
        lower = user_text.lower()

        # Контекст: ждём имя/подтверждение от кого ждать обратного звонка
        # Любой ответ принимаем как имя — это конец разговора
        if state.awaiting_callback_name:
            state.awaiting_callback_name = False
            return SCRIPT["secretary_callback_thanks"], "gave_name"

        # Контекст: секретарь продиктовал номер ответственного, по которому
        # мы перезвоним САМИ — записываем и завершаем (звонок не ждём, имя не нужно)
        if state.awaiting_record_number:
            state.awaiting_record_number = False
            return SCRIPT["secretary_gave_both"], "gave_number"

        # Кейс 4: получили должность ответственного (после имени и номера) → закрываем
        if state.secretary_role_pending:
            state.secretary_role_pending = False
            return SCRIPT["secretary_gave_both"], "gave_role"

        # Контекст: отказали дать номер, мы спросили «как ещё с ним связаться» —
        # принимаем любой ответ и вежливо завершаем (не давим дальше).
        if state.secretary_reach_asked:
            state.secretary_reach_asked = False
            return SCRIPT["secretary_callback_thanks"], "reach_answer"

        # Контекст: собеседник ДИКТУЕТ номер (в т.ч. по частям — «девятьсот
        # пятнадцать… четыреста шестьдесят пять»). Пока идут цифры/числа прописью —
        # МОЛЧА записываем (робот сказал «записываю» и слушает) и НИКОГДА не
        # диктуем свой номер. Терпеливо ждём: закрываемся не на первой же не-цифре,
        # а только когда собеседник явно закончил («всё», «записали?», прощание)
        # или дал две подряд не-числовые реплики.
        if state.secretary_collecting_number:
            if _is_dictating_number(user_text) or _is_bare_number_echo(lower) \
                    or _is_hold_request(lower):
                state.collecting_idle = 0
                return "", "recording_number"          # молчим, продолжаем запись
            done_words = any(p in lower for p in (
                "всё", "все", "это всё", "это все", "записал", "записали", "достаточно",
                "спасибо", "звоните", "перезвон", "и всё", "и все", "готово",
            ))
            state.collecting_idle += 1
            if done_words or state.collecting_idle >= 2:
                state.secretary_collecting_number = False
                state.collecting_idle = 0
                return SCRIPT["secretary_number_saved"], "gave_number"
            # Возможно, между цифрами вставили слово — даём ещё один шанс, молчим.
            return "", "recording_number"

        # Кейс 4: ждали номер по названному имени.
        if state.secretary_name_pending_number:
            # Начали диктовать номер (цифрами или прописью) — записываем, не
            # диктуем свой и не переспрашиваем имя (его уже назвали).
            if _is_dictating_number(user_text):
                state.secretary_name_pending_number = False
                state.secretary_collecting_number = True
                return SCRIPT["secretary_recording"], "recording_number"
            # «Номер телефона…» — секретарь начинает диктовать, а не отказывает.
            # НЕ закрываем и НЕ диктуем свой номер — ждём цифры на следующем шаге.
            if _is_bare_number_echo(lower):
                return SCRIPT["await_their_number"], "await_their_number"
            # «Запишите номер / вот номер» — готов диктовать: режим записи.
            if _offers_their_number(lower):
                state.secretary_name_pending_number = False
                state.secretary_collecting_number = True
                state.collecting_idle = 0
                return SCRIPT["secretary_recording"], "recording_number"
            # Отказали дать номер («нет», «не дам», «не скажу») — не прощаемся
            # сразу, а спрашиваем, как иначе связаться / переговорить с человеком.
            state.secretary_name_pending_number = False
            if _is_rejection(lower) or bool(
                set(re.findall(r"[а-яё]+", lower)) & {"нет", "неа", "нету", "не"}
            ):
                state.secretary_reach_asked = True
                return SCRIPT["secretary_how_to_reach"], "how_to_reach"
            # Иной ответ (не номер, но и не отказ) — закрываем как обычно
            return SCRIPT["secretary_gave_both"], "gave_number"

        # Контекст: ответственный отсутствует — мы спросили «когда будет, как зовут,
        # прямой номер». Принимаем имя/номер, НЕ переспрашиваем «кто отвечает».
        if state.secretary_absent_pending:
            name_here = _looks_like_person_name(user_text)
            if name_here:
                nm = _extract_responsible_name(user_text)
                if nm:
                    state.qual_data["name"] = nm
                state.secretary_name_known = True
            have_name = state.secretary_name_known or bool(state.qual_data.get("name"))

            # Ждали только имя (после «звоните на этот же номер») → закрываем
            if state.secretary_absent_wrapup:
                state.secretary_absent_wrapup = False
                state.secretary_absent_pending = False
                return SCRIPT["secretary_callback_same_number"], "callback_same_number"
            # Диктуют НОВЫЙ номер (цифрами или прописью) → записываем
            if _is_dictating_number(user_text):
                state.secretary_absent_pending = False
                state.secretary_collecting_number = True
                return SCRIPT["secretary_recording"], "recording_number"
            # «Звоните на этот же номер / по тому же» — контакт уже дан.
            # Если имя уже знаем — всё нужное получили, прощаемся. Иначе просим
            # только имя (прямой номер повторно НЕ просим).
            if _says_call_here(lower):
                state.secretary_absent_pending = False
                if have_name:
                    return SCRIPT["secretary_callback_same_number"], "callback_same_number"
                state.secretary_absent_pending = True
                state.secretary_absent_wrapup = True
                return SCRIPT["secretary_same_number_ask_name"], "same_number_ask_name"
            # Назвали имя (в т.ч. с отчеством) → просим прямой номер
            if name_here:
                state.secretary_absent_pending = False
                state.secretary_name_pending_number = True
                return SCRIPT["secretary_gave_name"], "gave_name"
            # Ни имени, ни номера («раньше утром», «не знаю») — один раз чётко
            # просим имя и прямой номер, затем вежливо завершаем.
            if not state.secretary_absent_name_asked:
                state.secretary_absent_name_asked = True
                return SCRIPT["secretary_absent_tomorrow"], "absent_ask_name_phone"
            state.secretary_absent_pending = False
            return SCRIPT["secretary_callback_thanks"], "absent_close"

        # «А вы кто?» / «Какая компания?» — ЕДИНСТВЕННЫЙ повод представиться заново.
        if _asks_who_are_you(lower):
            return SCRIPT["who_are_you_secretary"], "who_are_you"

        # Собеседник предлагает / готов дать номер ответственного («я могу вам
        # номер телефона», «запишите номер», «есть номер управляющего») — сразу
        # переходим в режим записи (говорим «записываю» и молчим), НЕ диктуем свой
        # и НЕ вываливаем пичт. Проверяем ДО cant_connect/wont_connect: реплика
        # «я не могу соединить, но могу дать номер» — это готовность дать контакт.
        # Голую диктовку цифр принимаем только если сами просили номер (иначе
        # «отдел двадцать шесть» в названии примут за номер).
        if _offers_their_number(lower) or (
            _is_dictating_number(user_text)
            and _robot_asked_their_number(state.last_robot_text)
        ):
            state.secretary_collecting_number = True
            state.collecting_idle = 0
            return SCRIPT["secretary_recording"], "recording_number"

        # «Номер телефона…» в ответ на нашу просьбу дать ИХ номер — приглашаем
        # продиктовать, но НЕ диктуем свой (его как раз хотели нам дать).
        if _is_bare_number_echo(lower) and _robot_asked_their_number(state.last_robot_text):
            return SCRIPT["await_their_number"], "await_their_number"

        # Приоритетная проверка сигналов передачи трубки (без вызова ИИ).
        # ВАЖНО: исключаем отрицания — «не соединяем», «не переведу», «не переключаем»
        # содержат подстроки сигналов передачи, но означают ОТКАЗ соединять.
        negated_connect = any(n in lower for n in (
            "не соедин", "не перевед", "не переключ",
        ))
        if not negated_connect and any(sig in lower for sig in TRANSFER_SIGNALS):
            return self._do_transfer(state, "transfer_signal")

        # ВАЖНО: одни лишь сигналы «поднятия трубки» («алло», «слушаю», «да-да»)
        # НЕ означают, что нас перевели на ЛПР — так отвечает и сам секретарь.
        # Раньше это приводило к преждевременному «меня направили к вам, всё верно?»
        # без реального перевода. Приветствие ЛПР говорим только после явного
        # перевода (сигнал перевода выше или ручной switch_to_lpr → «соединяю»).
        #
        # «Алло», «слушаю», «бизнес-центр, здравствуйте» после нашей первой
        # реплики почти всегда означают, что человек ТОЛЬКО ЧТО взял трубку и
        # приветствия не слышал (перед ним играло голосовое меню или трубку
        # передали). Поэтому представляемся заново — иначе собеседник слышит
        # «звоню по обязательным проверкам…» и не понимает даже, кто звонит.
        if not negated_connect and (
            _matches_signal(lower, LPR_PICKUP_SIGNALS)
            or _is_pickup_greeting(lower)
            or _is_company_greeting(lower)
        ):
            # Представление организации («бизнес-центр, здравствуйте») — человек
            # ТОЛЬКО взял трубку и вопроса не слышал: коротко переспрашиваем суть.
            # Пустой отклик («да», «добрый», «слушаю») сразу после нашего вопроса —
            # он услышал, но ещё НЕ ответил: молча ждём ответ (не переспрашиваем и
            # не перефразируем — «кто отвечает?» уже прозвучало). При затянувшемся
            # молчании watchdog мягко повторит вопрос.
            pure_ack = not _is_company_greeting(lower)
            if pure_ack and state.secretary_reintroduced < 1:
                state.secretary_reintroduced += 1
                return "", "await_answer"
            if state.secretary_reintroduced < 2:
                state.secretary_reintroduced += 1
                return SCRIPT["secretary_reask_responsible"], "reintroduce"
            return SCRIPT["secretary_what_do_you_want"], "pickup_no_transfer"

        # Эвристика: "я сам соединю/переведу" — обещание на будущее, не реальный перевод
        if any(p in lower for p in _SELF_CONNECT_PATTERNS):
            return SCRIPT["secretary_call_back"], "call_back"

        # Секретарь предлагает говорить с ним напрямую — минуем "меня направили к вам"
        if any(p in lower for p in SPEAK_WITH_ME_SIGNALS):
            state.phase = "lpr_greeting"
            return SCRIPT["lpr_confirmed_q"], "speak_with_me"

        # Сам собеседник оказался ответственным («я отвечаю», «это я», «я энергетик») —
        # не просим соединить с ним, а сразу спрашиваем имя и идём по сценарию ЛПР.
        # Голое «я» / «это я» тоже считаем таким ответом, если робот только что
        # спросил, кто отвечает за электрохозяйство (иначе одиночное «я» неоднозначно).
        asked_responsible = "электрохозяйств" in state.last_robot_text.lower()
        bare_i_am = re.fullmatch(
            r"(ну\s+)?(да[,\s]+)?(это\s+)?(я|я\s+сам[а]?|я\s+и\s+я)",
            lower.strip().rstrip(".!?"),
        ) is not None
        if "не отвечаю" not in lower and (
            any(p in lower for p in _I_AM_RESPONSIBLE)
            or (bare_i_am and asked_responsible)
        ):
            # Если собеседник назвал имя в той же реплике («Я отвечаю, Иван
            # Иванович») — не переспрашиваем имя, сразу переходим к теме
            name = _extract_responsible_name(user_text)
            if name:
                state.phase = "lpr_main"
                state.lpr_topic_asked = True
                state.lpr_topic_q_pending = True
                return (
                    f"{name}, очень приятно! У меня вопрос по испытаниям "
                    "электросетей — проверка сопротивления изоляции, "
                    "проверка металлосвязи. По этой теме с вами можно переговорить?",
                    "i_am_lpr_named",
                )
            # Имя не назвали — НЕ представляемся заново («меня направили к вам»),
            # сразу спрашиваем имя и переходим к теме звонка (без двойного «добрый день»)
            state.phase = "lpr_main"
            state.lpr_topic_asked = True
            state.lpr_topic_q_pending = True
            return SCRIPT["secretary_i_am_lpr_topic"], "i_am_lpr"

        # Просят НАШУ почту — даём email
        if _asks_our_email(lower):
            return SCRIPT["our_email"], "ask_our_email"

        # Контекст под-вопроса "не могу соединить"
        if state.secretary_cant_connect_asked:
            state.secretary_cant_connect_asked = False
            # Любой ответ — обрабатываем как уточнение
            if any(w in lower for w in ("нет", "не будет", "отсутствует", "уехал", "совещан")):
                return SCRIPT["secretary_not_present"], "secretary_not_present"
            return SCRIPT["secretary_refuses_connect"], "secretary_refuses_connect"

        # boss_no_connect шаг 2: получили ответ про техотчёт → подводим к ответственному
        if state.secretary_boss_report_asked:
            state.secretary_boss_report_asked = False
            state.secretary_boss_contact_asked = True
            return SCRIPT["secretary_boss_need_responsible"], "boss_need_responsible"

        # boss_no_connect шаг 3: ждали контакт. Дали номер → закрываем,
        # иначе (отказ передать) — просим прямую почту и имя ответственного
        if state.secretary_boss_contact_asked:
            state.secretary_boss_contact_asked = False
            if any(ch.isdigit() for ch in user_text):
                return SCRIPT["secretary_gave_both"], "gave_number"
            return SCRIPT["secretary_boss_email_name"], "boss_email_name"

        # Контекст под-вопроса "всё хорошо" — спросили должность
        if state.secretary_all_good_asked:
            state.secretary_all_good_asked = False
            if any(w in lower for w in ("секретарь", "администратор", "офис-менеджер", "помощник")):
                # Секретарь — ищем ответственного
                return SCRIPT["secretary_not_responsible"], "secretary_not_responsible"
            # Иначе считаем что он может быть ответственным
            return SCRIPT["secretary_responsible_confirmed"], "secretary_responsible_confirmed"

        # Кейс 5 (шаг 2): спросили должность после «что будете делать со сроками».
        # Признаётся, что не отвечает → объясняем, зачем нужен ответственный
        if state.secretary_role_asked:
            state.secretary_role_asked = False
            negative_role = any(p in lower for p in (
                "не отвечаю", "не я", "секретарь", "менеджер", "администратор",
                "офис-менеджер", "помощник", "ресепшн", "на ресепшн",
            )) or bool(set(re.findall(r"[а-яё]+", lower)) & {"нет", "неа", "нету"})
            if negative_role:
                return SCRIPT["secretary_not_understand_responsible"], "role_not_responsible"
            # Иначе считаем, что он может быть ответственным
            return SCRIPT["secretary_responsible_confirmed"], "secretary_responsible_confirmed"

        # Кейс 5 (шаг 1): «и что вы будете делать, когда узнаете сроки?»
        if any(p in lower for p in (
            "что вы будете делать", "что будете делать", "что вы дальше будете",
            "что потом будете", "что вы с этим", "что это вам даст",
            "что вам это даст", "что вы будете с этим", "что дальше будете",
            "что вы с этими сроками", "зачем вам сроки",
        )):
            state.secretary_role_asked = True
            return SCRIPT["secretary_what_will_you_do"], "secretary_what_will_you_do"

        # Кейс 2: «я не могу вам ответить на данный вопрос» / «ничем не могу помочь» —
        # оставляем контакты для директора / другого специалиста
        if "не могу соедин" not in lower and any(p in lower for p in (
            "не могу вам ответить", "не могу ответить", "не могу вам помочь",
            "не могу помочь", "ничем не могу помочь", "не могу подсказать",
            "не могу с этим помочь", "не уполномочен", "не в моей компетенц",
        )):
            return SCRIPT["secretary_dont_understand"], "dont_understand"

        # «По какому вопросу звоните?» / «Что вы хотели?» — цель звонка, а НЕ запрос
        # нашего номера. Ловим детерминированно, чтобы ИИ не спутал с ask_our_number
        # (иначе робот преждевременно диктует наш телефон).
        if any(p in lower for p in (
            "по какому вопросу", "по какому поводу", "по какому делу",
            "что вы хотели", "что хотели", "чем могу помочь", "чем помочь",
            "что вас интересует", "с чем звоните", "какой у вас вопрос",
            "какой вопрос", "что вам нужно", "что нужно",
        )):
            return SCRIPT["secretary_what_do_you_want"], "what_do_you_want"

        # «Перезвоните позже» — просьба перезвонить (не даём ей уйти в «затрудняюсь»)
        if _is_callback_request(lower):
            if state.secretary_name_known:
                return SCRIPT["secretary_call_back_name_known"], "call_back"
            return SCRIPT["secretary_call_back"], "call_back"

        # «Директор, но его нет», «в отпуске», «его в данный момент нету» —
        # ответственный известен, но сейчас недоступен. Просить «соедините меня
        # с ним» бессмысленно и выглядит так, будто робот не слушал: сразу
        # узнаём имя, когда будет и прямой номер.
        asked_to_connect = any(
            w in state.last_robot_text.lower() for w in ("соедините", "соединить")
        )
        names_role = any(r in lower for r in _RESPONSIBLE_ROLE_WORDS)
        if _is_absence(lower) and (state.secretary_name_known or asked_to_connect
                                   or names_role):
            state.secretary_name_known = True
            return SCRIPT["secretary_not_present"], "not_present"

        # «У нас отвечает инженер», «есть энергетик» — ответственный есть.
        # Проверяем до ИИ: при промахе классификатора такой ответ уходил в
        # переспрос, хотя секретарь уже назвал должность.
        if not _is_rejection(lower) and any(r in lower for r in _ROLE_WORDS):
            state.secretary_name_known = True
            return SCRIPT["secretary_connect_responsible"], "has_responsible"

        # Детерминированная классификация высокосигнальных фраз — минуем ИИ
        code = _keyword_intent(lower)
        if code is None:
            code = await self._classify_secretary(
                user_text, state.last_robot_text,
                state.recent_exchanges, state.negative_turn_count,
            )

        if code == "transfer_to_lpr":
            return self._do_transfer(state, code)

        if code == "speak_with_me":
            state.phase = "lpr_greeting"
            return SCRIPT["lpr_confirmed_q"], code

        if code == "off_topic":
            return SCRIPT["off_topic_response"], code

        if code == "what_do_you_want":
            return SCRIPT["secretary_what_do_you_want"], code

        if code == "has_responsible":
            state.secretary_name_known = True
            return SCRIPT["secretary_connect_responsible"], code

        if code == "no_engineer":
            # Должность уже называли («директор») — предлагать список
            # «директор, инженер, энергетик или завхоз» значит не слушать
            # собеседника. Спрашиваем, когда будет и как связаться.
            if state.secretary_name_known:
                return SCRIPT["secretary_not_present"], "not_present"
            return SCRIPT["secretary_no_engineer"], code

        if code == "why_need_person":
            return SCRIPT["secretary_why_need_person"], code

        if code == "dont_need_services":
            return SCRIPT["secretary_dont_need_services"], code

        if code == "renting":
            return SCRIPT["secretary_renting"], code

        if code == "inspecting_body":
            return SCRIPT["secretary_inspecting_body"], code

        if code == "documents":
            return SCRIPT["secretary_documents"], code

        if code == "send_email":
            return SCRIPT["secretary_send_email"], code

        if code == "want_to_offer":
            return SCRIPT["secretary_not_offer"], code

        if code == "recently_communicated":
            return SCRIPT["secretary_recently_communicated"], code

        if code == "all_good":
            state.secretary_all_good_asked = True
            return SCRIPT["secretary_all_good"], code

        if code == "wont_connect":
            return SCRIPT["secretary_wont_connect"], code

        if code == "cant_connect":
            state.secretary_cant_connect_asked = True
            return SCRIPT["secretary_cant_connect"], code

        if code == "not_present":
            return SCRIPT["secretary_not_present"], code

        if code == "refuses_connect":
            return SCRIPT["secretary_refuses_connect"], code

        if code == "everything_fine":
            return SCRIPT["secretary_everything_fine"], code

        if code == "we_dont_do":
            return SCRIPT["secretary_we_dont_do"], code

        if code == "have_contract":
            return SCRIPT["secretary_have_contract"], code

        if code == "dont_understand":
            return SCRIPT["secretary_dont_understand"], code

        if code == "relay_message":
            return SCRIPT["secretary_relay_message"], code

        if code == "call_back":
            if state.secretary_name_known:
                return SCRIPT["secretary_call_back_name_known"], code
            return SCRIPT["secretary_call_back"], code

        if code == "wrong_number":
            return SCRIPT["secretary_wrong_number"], code

        if code == "boss_no_connect":
            state.secretary_boss_report_asked = True
            return SCRIPT["secretary_boss_no_connect"], code

        if code == "wrong_dept":
            return SCRIPT["secretary_wrong_dept"], code

        if code == "gave_name":
            state.secretary_name_known = True
            state.secretary_name_pending_number = True
            return SCRIPT["secretary_gave_name"], code

        if code == "gave_number":
            return SCRIPT["secretary_gave_both"], code

        if code == "ask_our_number":
            state.awaiting_callback_name = True
            return SCRIPT["secretary_give_our_number"], code

        if code == "what_inspections":
            return SCRIPT["secretary_what_inspections"], code

        if code == "who_do_you_need":
            return SCRIPT["secretary_who_do_you_need"], code

        if code == "says_record":
            # Секретарь диктует номер ответственного — переходим в режим записи
            # (говорим «записываю» и МОЛЧА принимаем цифры), а не диктуем свой.
            state.secretary_collecting_number = True
            state.collecting_idle = 0
            return SCRIPT["secretary_recording"], "recording_number"

        if code == "phone_source":
            return SCRIPT["lpr_phone_source"], code

        if code == "address_question":
            return SCRIPT["lpr_address"], code

        if code == "other_org":
            return self._handle_other_org(state, user_text)

        # Фоллбэк
        if state.unknown_streak >= 2:
            return SCRIPT["secretary_dont_understand"], "unknown_limit"
        return SCRIPT["fallback_secretary"], "unknown"

    def _handle_other_org(self, state: V2SessionState, user_text: str) -> tuple[str, str]:
        """«Этим занимается другая организация, звоните туда».

        Если номер продиктовали сразу — записываем и прощаемся; если нет —
        просим номер (следующая реплика будет обработана как продиктованный
        контакт через ``awaiting_record_number``).
        """
        if sum(ch.isdigit() for ch in user_text) >= 6:
            return SCRIPT["secretary_gave_both"], "other_org_number"
        state.awaiting_record_number = True
        return SCRIPT["secretary_other_org"], "other_org"

    def _do_transfer(self, state: V2SessionState, code: str) -> tuple[str, str]:
        state.phase = "lpr_greeting"
        state.lpr_greeted = False
        return SCRIPT["lpr_greeting"], code

    # ── Фаза: Приветствие ЛПР ─────────────────────────────────────────────────

    async def _handle_lpr_greeting(self, state: V2SessionState, user_text: str) -> tuple[str, str]:
        lower = user_text.lower()

        # «А вы кто?» — представляемся заново (единственный повод).
        if _asks_who_are_you(lower):
            return SCRIPT["who_are_you_lpr"], "who_are_you"

        # Просят НАШУ почту («продиктуйте свою почту») → даём email
        if _asks_our_email(lower):
            return SCRIPT["our_email"], "ask_our_email"

        # «Перезвоните позже» — просьба перезвонить (а не «затрудняюсь ответить»)
        if _is_callback_request(lower):
            return SCRIPT["lpr_call_back"], "call_back"

        # Кейс 4: «зачем вам моё имя?» на шаге «как могу к вам обращаться?» —
        # объясняем, кто мы, и сразу переходим к теме планов работ
        if any(p in lower for p in (
            "зачем вам мо", "зачем вам имя", "зачем имя", "зачем моё имя",
            "зачем мое имя", "для чего вам имя", "для чего имя", "зачем вам знать",
            "зачем вам как", "зачем имя нужно", "имя зачем", "к чему вам имя",
        )):
            state.phase = "lpr_main"
            state.lpr_topic_asked = True
            return SCRIPT["lpr_why_my_name"], "why_my_name"

        # «Да, я энергетик» / «Да, отвечаю» / «Да» — подтверждение без похода в ИИ.
        # Раньше такие ответы при промахе классификатора уходили в переспрос.
        if "не отвечаю" not in lower and not _is_rejection(lower) and (
            any(p in lower for p in _I_AM_RESPONSIBLE)
            or bool(set(re.findall(r"[а-яёa-z]+", lower)) & _TOPIC_AFFIRM)
        ):
            state.phase = "lpr_main"
            state.lpr_topic_asked = True
            if state.last_robot_text == SCRIPT["lpr_confirmed_q"]:
                return SCRIPT["fallback_lpr"], "lpr_confirmed_direct"
            return SCRIPT["lpr_confirmed_q"], "lpr_confirmed"

        # Детерминированная классификация высокосигнальных фраз — минуем ИИ.
        # В фазе приветствия ЛПР обрабатываем только релевантные коды.
        kw = _keyword_intent(lower)
        if kw in ("send_email", "want_to_offer", "wont_connect", "boss_no_connect"):
            code = kw
        else:
            code = await self._classify_lpr_greeting(
                user_text, state.last_robot_text, state.recent_exchanges,
            )
            # Робот спросил «Как могу к вам обращаться?» — короткий ответ-имя
            # («Татьяна», «Меня зовут Сергей») означает готовность говорить
            if code in ("unknown", "what_do_you_want") and _looks_like_name(user_text):
                code = "confirmed"

        if code == "confirmed":
            state.phase = "lpr_main"
            state.lpr_topic_asked = True
            # speak_with_me path: lpr_confirmed_q уже был сказан — не повторяем,
            # сразу задаём главный вопрос
            if state.last_robot_text == SCRIPT["lpr_confirmed_q"]:
                return SCRIPT["fallback_lpr"], "lpr_confirmed_direct"
            return SCRIPT["lpr_confirmed_q"], "lpr_confirmed"

        if code == "wrong_person":
            return SCRIPT["lpr_wrong_person"], "lpr_wrong_person"

        if code == "send_email":
            return SCRIPT["secretary_send_email"], code

        if code == "want_to_offer":
            return SCRIPT["secretary_not_offer"], code

        if code == "recently_communicated":
            return SCRIPT["secretary_recently_communicated"], code

        if code == "wont_connect":
            return SCRIPT["secretary_wont_connect"], code

        if code == "boss_no_connect":
            # Это снова привратник — возвращаемся к фазе секретаря и ведём
            # пошаговый сценарий "руководитель сказал не соединять"
            state.phase = "secretary"
            state.secretary_boss_report_asked = True
            return SCRIPT["secretary_boss_no_connect"], code

        if code == "documents":
            return SCRIPT["secretary_documents"], code

        if code == "what_do_you_want":
            return SCRIPT["secretary_what_do_you_want"], code

        if code == "off_topic":
            return SCRIPT["off_topic_response"], code

        # unknown/неясный ответ — уточняющий вопрос (без "меня направили к вам")
        return SCRIPT["lpr_greeting_retry"], "lpr_greeting_repeat"

    # ── Фаза: ЛПР основная ────────────────────────────────────────────────────

    async def _handle_lpr_main(self, state: V2SessionState, user_text: str) -> tuple[str, str]:
        lower = user_text.lower()

        # «А вы кто?» — представляемся заново (единственный повод), остаёмся в теме.
        if _asks_who_are_you(lower):
            return SCRIPT["who_are_you_lpr"], "who_are_you"

        # «Номер телефона…» в ответ на нашу просьбу дать ИХ номер — приглашаем
        # продиктовать, а не диктуем свой.
        if _is_bare_number_echo(lower) and _robot_asked_their_number(state.last_robot_text):
            return SCRIPT["await_their_number"], "await_their_number"

        # Кейс 1: «зачем вам мой телефон?» когда мы ждём прямой номер —
        # объясняем причину и остаёмся в режиме ожидания номера
        if _asks_why_phone(lower) and (
            state.lpr_far_date_pending
            or state.fd_step == 7
            or state.last_robot_text in (SCRIPT["lpr_fd_phone"], SCRIPT["lpr_far_date"])
        ):
            return SCRIPT["why_need_phone"], "why_need_phone"

        # Кейс 4: только что задали тему-вопрос (персональное приветствие по имени).
        # Согласие → переходим к вопросу о планах; иначе обрабатываем как обычно.
        if state.lpr_topic_q_pending:
            state.lpr_topic_q_pending = False
            tokens = set(re.findall(r"[а-яёa-z]+", lower))
            if tokens & _TOPIC_AFFIRM:
                return self._after_topic_confirmed(state, lower)

        # Кейс 5: отработка отказов на офферы по «своей компании / подрядчику».
        # 1-й заход (10% ниже) → отказ → «вы же всё равно мониторите рынок» +
        # сразу спрашиваем сроки испытаний.
        if state.last_robot_text == SCRIPT["lpr_own_company_1"] and _is_rejection(lower):
            state.lpr_own_company_attempt = max(state.lpr_own_company_attempt, 2)
            state.lpr_oc2_asked = True
            return SCRIPT["lpr_own_company_2"], "own_company_2"

        # Кейс 5 (шаг 4/5): после «мониторите рынок» ждём сроки испытаний.
        # «Позвоните в конце года / в следующем году» / дальний срок → берём
        # прямой номер и лучший месяц; близкий срок → оформляем заявку.
        if state.lpr_oc2_asked:
            state.lpr_oc2_asked = False
            if _work_timeframe(lower) == "near":
                state.phase = "qualification"
                state.qual_step = 0
                return SCRIPT["qual_step0"], "oc2→qual0"
            # Дальний срок или «позвоните позже» — просим прямой номер и месяц.
            state.lpr_far_date_pending = True
            return SCRIPT["lpr_own_company_far"], "own_company_far"

        # Цепочка уточнений при дальних сроках (кейсы 5, 6 и далее)
        if state.fd_step > 0:
            return self._advance_fd(state, user_text)

        # Дальний срок: спросили «когда рассматриваете подрядчиков?» —
        # любой ответ ведём в цепочку уточнений начиная с периодичности
        if state.lpr_far_contractor_asked:
            state.lpr_far_contractor_asked = False
            state.fd_step = 2
            return SCRIPT["lpr_fd_periodicity"], "far_contractor→periodicity"

        # Дальний срок: ждём прямой номер для связи ближе к срокам.
        # Получив номер (или «звоните на этот») — закрываем без «свяжется специалист».
        # Срабатывает и по флагу, и по последней реплике (на случай, если флаг не выставлен)
        if state.lpr_far_date_pending or state.last_robot_text == SCRIPT["lpr_far_date"]:
            if any(ch.isdigit() for ch in user_text) or _says_same_number(lower):
                state.lpr_far_date_pending = False
                state.phase = "closed"
                return SCRIPT["lpr_far_date_close"], "far_date_closed"
            if any(w in lower for w in ("запишите", "записывайте", "диктую", "записывай")):
                return SCRIPT["lpr_far_date_get_number"], "far_date_record"
            # Иной ответ — выходим из режима ожидания, обрабатываем как обычно
            state.lpr_far_date_pending = False

        # Контекст: спросили «когда проводили работы в последний раз» —
        # запускаем цепочку уточняющих вопросов (кейсы 5 и 6).
        if state.lpr_last_works_asked:
            state.lpr_last_works_asked = False
            uncertain = any(p in lower for p in (
                "не помню", "не знаю", "не в курсе", "затрудняюсь",
                "сложно сказать", "не скажу", "давно", "не помн",
            ))
            if uncertain:
                # «Не помню» → предлагаем посмотреть техотчёт и созвониться позже
                state.fd_step = 1
                return SCRIPT["lpr_fd_check_report"], "fd_check_report"
            # Конкретный ответ → сразу к периодичности
            state.fd_step = 2
            return SCRIPT["lpr_fd_periodicity"], "fd_periodicity_start"

        # Контекст: спросили «своя лицензия или подрядчик?» («мы сами проводим работы»)
        if state.lpr_works_clarify_asked:
            state.lpr_works_clarify_asked = False
            if any(p in lower for p in (
                "подрядчик", "компани", "нанима", "сторонн", "аутсорс",
                "заказыва", "привлека", "делает нам", "нам делает", "другая",
                "не сами", "не своя", "работаем с", "с компан",
            )):
                # Это подрядчик — работаем как со «своей компанией»
                state.lpr_own_company_attempt = max(state.lpr_own_company_attempt, 1)
                return SCRIPT["lpr_own_company_1"], "own_lab_contractor"
            # Нет лицензии, есть только своё оборудование («сами всё проверяем») —
            # спрашиваем про технический отчёт для проверяющих органов
            if any(p in lower for p in (
                "лицензии нет", "нет лицензии", "без лицензии", "не лицензир",
                "оборудовани", "приборами", "сами провер", "сами все провер",
                "сами всё провер", "сами себе провер",
            )):
                state.lpr_no_license_asked = True
                return SCRIPT["lpr_no_license_report"], "own_lab_no_license"
            # Иначе считаем, что у них своя лицензия → спрашиваем до скольких кВ
            state.lpr_own_etl_asked = True
            return SCRIPT["lpr_own_etl_license"], "own_lab_staff_license"

        # Контекст: спросили «отчёт запрашивают проверяющие?» (нет лицензии).
        # Любой ответ подводим к питчу про лицензированную лабораторию и просим номер.
        if state.lpr_no_license_asked:
            state.lpr_no_license_asked = False
            state.lpr_far_date_pending = True
            return SCRIPT["lpr_no_license_close"], "no_license_close"

        # Контекст: спросили «для чего нужно КП?» (после lpr_send_kp_clarify)
        if state.lpr_kp_clarify_asked:
            state.lpr_kp_clarify_asked = False
            if any(p in lower for p in ("бюджет", "заложен", "заложить", "планирован")):
                state.lpr_scope_asked = True
                return SCRIPT["lpr_kp_need_scope"], "kp_for_budget"
            if any(p in lower for p in (
                "планир", "рассматрива", "выбира", "собира", "сравн", "тендер",
                "закупк", "торг", "нужно для работ",
            )):
                state.phase = "qualification"
                state.qual_step = 0
                return SCRIPT["qual_step0"], "kp_planning→qual0"
            # «просто для понимания / посмотреть цены» → прайс + договорённость по срокам
            state.lpr_last_works_asked = True
            return SCRIPT["lpr_kp_for_understanding"], "kp_for_understanding"

        # Контекст: спросили «можете предоставить объём работ?» — берём контакт
        if state.lpr_scope_asked:
            state.lpr_scope_asked = False
            state.phase = "qualification"
            state.qual_step = 5
            return SCRIPT["qual_step5"], "scope→qual5"

        # Просят НАШУ почту («продиктуйте свою почту», «вашу почту») → даём email
        if _asks_our_email(lower):
            return SCRIPT["our_email"], "ask_our_email"

        # «Перезвоните позже» — просьба перезвонить (а не «затрудняюсь ответить»)
        if _is_callback_request(lower):
            return SCRIPT["lpr_call_back"], "call_back"

        # «КП для заложения бюджета» → нужен объём работ
        if (any(p in lower for p in (
            "кп", "коммерческ", "прайс", "смет", "скинь", "скинуть",
            "пришл", "отправ", "вышл",
        )) and any(p in lower for p in (
            "бюджет", "заложен", "заложить", "для планирован",
        ))):
            state.lpr_scope_asked = True
            return SCRIPT["lpr_kp_need_scope"], "kp_for_budget"

        # «У нас нет денег / бюджета» → уточняем срок выделения бюджета
        if any(p in lower for p in (
            "нет денег", "денег нет", "нет бюджета", "бюджета нет", "нет средств",
            "средств нет", "нет финансир", "не выделен бюджет", "бюджет не выделен",
            "нет финанс", "денежных средств нет",
        )):
            state.lpr_last_works_asked = True
            return SCRIPT["lpr_no_money"], "no_money"

        # Проверка на запрос нашего номера
        if any(w in lower for w in (
            "ваш номер", "ваш телефон", "ваш контакт",
            "продиктуйте", "оставьте контакт", "оставьте свой", "оставьте номер",
            "свой номер", "свой телефон",
            "наберём вас", "наберем вас", "наберёт вас", "наберет вас",
            "перезвоним вам", "перезвонит вам", "специалист позвон", "специалист набер",
        )):
            return SCRIPT["our_phone"], "ask_our_number"

        # Проверка на "запишите" — ЛПР диктует свой номер
        if any(w in lower for w in ("запишите", "записывайте", "записываю", "диктую")):
            return SCRIPT["lpr_far_date_get_number"], "says_record"

        # Детерминированные высокосигнальные фразы (адрес / источник номера)
        kw = _keyword_intent(lower)
        if kw == "phone_source":
            return SCRIPT["lpr_phone_source"], kw
        if kw == "address_question":
            return SCRIPT["lpr_address"], kw

        # «У нас своя лаборатория / электролаборатория» → уточняем: своя в штате
        # или подрядчик, с которым работают. Дальше это ведёт в ту же развилку,
        # что и «сами проводим» (lpr_works_clarify_asked).
        if any(p in lower for p in (
            "своя лаборатория", "своя электролаборатория", "своя этл",
            "собственная лаборатория", "наша лаборатория", "наша электролаборатория",
            "есть лаборатория", "имеется лаборатория", "своя лаба",
            "у нас лаборатория", "у нас электролаборатория",
        )):
            state.lpr_works_clarify_asked = True
            return SCRIPT["lpr_own_lab_clarify"], "own_lab_staff"

        # «Мы сами проводим такие работы / своими силами» → уточняем лицензию/подрядчика
        if any(p in lower for p in (
            "сами проводим", "сами делаем", "сами это делаем", "своими силами",
            "сами выполняем", "сами справляемся",
        )):
            state.lpr_works_clarify_asked = True
            return SCRIPT["lpr_works_clarify"], "own_lab_staff"

        # Только что задали тему-вопрос ("по этой теме можно переговорить?") —
        # распознаём согласие и переходим к вопросу о планах (а не уходим в debug)
        if state.last_robot_text == SCRIPT["lpr_confirmed_q"]:
            tokens = set(re.findall(r"[а-яёa-z]+", lower))
            if tokens & _TOPIC_AFFIRM:
                return self._after_topic_confirmed(state, lower)

        # Ответ на «Планируете проведение испытаний в ближайшее время?» —
        # отрицание: не уходим сразу в сбор номера, а уточняем прошлые работы
        if state.last_robot_text == SCRIPT["fallback_lpr"]:
            neg_phrase = any(p in lower for p in (
                "пока нет", "не планир", "не скоро", "не в ближайш", "ещё нет",
                "еще нет", "нескоро", "не сейчас", "позже", "потом",
            ))
            neg_word = bool(set(re.findall(r"[а-яё]+", lower)) & {"нет", "неа", "нету"})
            if neg_phrase or neg_word:
                state.lpr_last_works_asked = True
                return SCRIPT["lpr_when_last_works"], "lpr_when_last_works"

        # Кейс 3: «работы проводит / за всё отвечает управляющая компания»
        if any(p in lower for p in (
            "управляющая компания", "управляющей компани", "управляющую компани",
            "управляющая комп", "управляйка", "наша ук", "через ук",
        )):
            return SCRIPT["lpr_management_company"], "management_company"

        # Кейс 4: «работы проводит / за всё отвечает Энергосбыт»
        if "энергосбыт" in lower:
            return SCRIPT["lpr_energosbyt"], "energosbyt"

        # Кейс 2: «зачем вам такая информация?» — отвечаем как электротехническая
        # лаборатория и снова спрашиваем про сроки работ
        if _asks_why_info(lower):
            return SCRIPT["lpr_propose_works"], "propose_works"

        # Кейс 1: «такие работы никогда не делали/не проводили»
        if "никогда" in lower and any(p in lower for p in (
            "не делал", "не провод", "не занимал", "не выполнял",
        )):
            return SCRIPT["secretary_we_dont_do"], "never_did_works"

        # Кейс 7: «работы уже провели/сделали» → уточняем, когда именно проводили
        if any(p in lower for p in (
            "уже провели", "уже сделали", "уже выполнили", "уже проводили",
            "провели работы", "сделали работы", "недавно провели",
            "недавно делали", "только что провели", "всё сделали", "все сделали",
        )):
            state.lpr_last_works_asked = True
            return SCRIPT["lpr_when_last_works"], "already_done→when_last_works"

        # Кейс 3: ЛПР называет дальний срок работ (> 2 мес.) в ответ на вопрос
        # о планах → это не заявка: спрашиваем, когда рассматривают подрядчиков
        if state.last_robot_text in (
            SCRIPT["fallback_lpr"], SCRIPT["lpr_propose_works"],
            SCRIPT["lpr_why_my_name"], SCRIPT["lpr_no_works"],
        ) and _work_timeframe(lower) == "far":
            return self._start_far_works(state)

        # Кейс 1: ЛПР подтверждает планы работ в ближайшее время → заявка
        if any(p in lower for p in (
            "планирую работ", "планируем работ", "собираем коммерческ",
            "собираем кп", "собираем сейчас", "собираем предложен",
            "подходят сроки", "подошли сроки", "да планир", "планируем провед",
            "сейчас собира", "сейчас планир",
        )) and _work_timeframe(lower) != "far":
            state.phase = "qualification"
            state.qual_step = 0
            return SCRIPT["qual_step0"], "works_planned_kw→qual0"

        code = await self._classify_lpr_main(
            user_text, state.last_robot_text, state.recent_exchanges,
        )

        if code == "address_question":
            return SCRIPT["lpr_address"], code

        if code == "phone_source":
            return SCRIPT["lpr_phone_source"], code

        if code == "propose_works":
            return SCRIPT["lpr_propose_works"], code

        if code == "send_kp":
            state.lpr_kp_clarify_asked = True
            return SCRIPT["lpr_send_kp_clarify"], code

        if code == "no_works":
            return SCRIPT["lpr_no_works"], code

        if code == "far_date":
            # Дальний срок → не заявка: спрашиваем, когда рассматривают подрядчиков
            return self._start_far_works(state)

        if code == "works_planned":
            # Близкий срок (≤2 мес.) → заявка; дальний → цепочка уточнений
            if _work_timeframe(lower) == "far":
                return self._start_far_works(state)
            state.phase = "qualification"
            state.qual_step = 0
            return SCRIPT["qual_step0"], "works_planned→qual0"

        if code == "own_company":
            attempt = state.lpr_own_company_attempt
            state.lpr_own_company_attempt += 1
            if attempt == 0:
                return SCRIPT["lpr_own_company_1"], code
            # Дальше — «вы же всё равно мониторите рынок» + вопрос про сроки.
            state.lpr_oc2_asked = True
            return SCRIPT["lpr_own_company_2"], code

        if code == "own_lab_staff":
            # «Мы сами проводим» — сначала уточняем: своя лицензия или подрядчик
            state.lpr_works_clarify_asked = True
            return SCRIPT["lpr_works_clarify"], code

        if code == "own_lab_contractor":
            # На самом деле это подрядчик — как "своя компания"
            return SCRIPT["lpr_own_company_1"], "own_lab_contractor"

        if code == "says_record":
            return SCRIPT["lpr_far_date_get_number"], code

        if code == "says_phone":
            return SCRIPT["qual_step6"], "phone_received"  # получили номер — закрываем

        if code == "ask_our_number":
            return SCRIPT["our_phone"], code

        if code == "off_topic":
            return SCRIPT["off_topic_response"], code

        # ЛПР упомянул лицензию (ответ на наш вопрос про ЭТЛ)
        if state.lpr_own_etl_asked:
            state.lpr_own_etl_asked = False
            return SCRIPT["lpr_our_license"], "lpr_license_response"

        if state.unknown_streak >= 2:
            return SCRIPT["fallback_lpr"], "unknown_limit"
        return SCRIPT["fallback_lpr"], "unknown"

    def _after_topic_confirmed(self, state: V2SessionState, lower: str) -> tuple[str, str]:
        """ЛПР согласился говорить по теме.

        Если в той же реплике назван срок работ («да, планируем в июне») —
        не переспрашиваем то, на что уже ответили, а идём дальше по сценарию.
        """
        timeframe = _work_timeframe(lower)
        if timeframe == "far":
            return self._start_far_works(state)
        if timeframe == "near":
            state.phase = "qualification"
            state.qual_step = 0
            return SCRIPT["qual_step0"], "topic_confirmed→qual0"
        return SCRIPT["fallback_lpr"], "lpr_topic_confirmed"

    def _start_far_works(self, state: V2SessionState) -> tuple[str, str]:
        """Дальний срок работ: спрашиваем, когда рассматривают подрядчиков."""
        state.lpr_far_contractor_asked = True
        return SCRIPT["lpr_far_contractor_when"], "far_works_start"

    def _advance_fd(self, state: V2SessionState, user_text: str) -> tuple[str, str]:
        """Цепочка уточняющих вопросов при дальних сроках (кейсы 3, 5, 6, 7).

        Шаги: 1=посмотреть техотчёт → 2=периодичность → 3=договор →
        4=кол-во зданий → 5=одновременно/в разное время →
        6=сроки по объектам → 8=примерные сроки (если не помнит) →
        7=прямой номер → закрытие.
        При «одновременно» на шаге 5 сразу переходим к запросу номера.
        """
        lower = user_text.lower()
        step = state.fd_step
        if step == 1:        # ответили на «посмотрите техотчёт» → периодичность
            state.fd_step = 2
            return SCRIPT["lpr_fd_periodicity"], "fd_periodicity"
        if step == 2:        # ответили на периодичность → договор
            state.fd_step = 3
            return SCRIPT["lpr_fd_contract"], "fd_contract"
        if step == 3:        # ответили на договор → кол-во зданий
            state.fd_step = 4
            return SCRIPT["lpr_fd_buildings"], "fd_buildings"
        if step == 4:        # ответили на кол-во зданий
            # Один объект → вопрос про одновременность не нужен, сразу к номеру
            if _is_single_building(lower):
                state.fd_step = 7
                return SCRIPT["lpr_fd_phone"], "fd_phone"
            state.fd_step = 5
            return SCRIPT["lpr_fd_simultaneous"], "fd_simultaneous"
        if step == 5:        # одновременно → сразу номер; в разное время → сроки объектов
            if any(p in lower for p in _SIMULTANEOUS_TERMS):
                state.fd_step = 7
                return SCRIPT["lpr_fd_phone"], "fd_phone"
            state.fd_step = 6
            return SCRIPT["lpr_fd_nearest_object"], "fd_nearest_object"
        if step == 6:        # сроки по объектам: «не помню» → примерно; иначе → номер
            if any(p in lower for p in _UNCERTAIN_TERMS):
                state.fd_step = 8
                return SCRIPT["lpr_fd_nearest_approx"], "fd_nearest_approx"
            state.fd_step = 7
            return SCRIPT["lpr_fd_phone"], "fd_phone"
        if step == 8:        # ответили на примерные сроки → номер
            state.fd_step = 7
            return SCRIPT["lpr_fd_phone"], "fd_phone"
        # step == 7: получили номер → завершаем
        state.fd_step = 0
        state.phase = "closed"
        return SCRIPT["lpr_fd_close"], "fd_close"

    # ── Фаза: Квалификация ────────────────────────────────────────────────────

    async def _handle_qualification(self, state: V2SessionState, user_text: str) -> tuple[str, str]:
        lower = user_text.lower()
        step = state.qual_step

        # Просят НАШУ почту — даём email
        if _asks_our_email(lower):
            return SCRIPT["our_email"], "ask_our_email"

        # «Перезвоните позже» — просьба перезвонить (а не «затрудняюсь ответить»)
        if _is_callback_request(lower):
            return SCRIPT["lpr_call_back"], "call_back"

        # Кейс 5: «а можно я вам задам пару вопросов?» — соглашаемся, остаёмся на шаге
        if any(p in lower for p in (
            "можно я задам", "могу задать", "можно задать", "задам вам",
            "задам пару", "задать пару", "задать вам", "вам задать",
            "можно вопрос", "можно я спрошу", "вам пару вопросов", "вам вопрос",
        )):
            return SCRIPT["lpr_let_them_ask"], "let_them_ask"

        # Кейс 2: получили ответ про ТЗ/сроки КП по площадке → закрываем
        if state.qual_platform_details_pending:
            state.qual_platform_details_pending = False
            state.phase = "closed"
            return SCRIPT["qual_contract_platform_close"], "qual3p_details→closed"

        # Проверка на запрос нашего номера в любом шаге квалификации
        if any(w in lower for w in (
            "ваш номер", "ваш телефон", "ваш контакт",
            "продиктуйте свой", "оставьте контакт", "оставьте свой", "оставьте номер",
            "свой номер", "свой телефон",
            "наберём вас", "наберем вас", "наберёт вас", "наберет вас",
            "перезвоним вам", "перезвонит вам", "специалист позвон", "специалист набер",
        )):
            return (
                SCRIPT["our_phone"] + " Будем рады принять звонок вашего специалиста! "
                "И всё же уточните — в каком месяце ориентировочно планируете провести работы?",
                "ask_our_number",
            )

        # Кейс 2: клиент задаёт встречный вопрос (адрес / откуда номер) —
        # отвечаем на него и тут же возвращаемся к текущему вопросу заявки
        side_kw = _keyword_intent(lower)
        if side_kw == "address_question":
            return (
                SCRIPT["lpr_address"] + " " + self._qual_current_question(state),
                "address_question",
            )
        if side_kw == "phone_source":
            return (
                SCRIPT["lpr_phone_source"] + " " + self._qual_current_question(state),
                "phone_source",
            )

        # Кейс 1: «зачем вам мой телефон?» на шаге запроса номера —
        # объясняем причину, оставаясь на шаге 5
        if step == 5 and _asks_why_phone(lower):
            return SCRIPT["why_need_phone"], "why_need_phone"

        # Шаги без классификатора (кол-во зданий, одновременность, сроки по объектам).
        # Детерминированно ловим срок работ (шаг 1) и срок выбора подрядчика (шаг 2),
        # чтобы не зацикливаться на повторе вопроса.
        if step in (4, 7, 8, 9):
            code = "_skip"
        elif step == 1:
            code = _qual_step1_intent(lower)
        elif step == 2:
            code = _qual_contractor_intent(lower)
        else:
            code = None
        if code is None:
            code = await self._classify_qualification(
                user_text, step, state.qual_platform_pending
            )

        if step == 0:
            if code == "agreement":
                state.qual_step = 1
                return SCRIPT["qual_step1"], "qual0→qual1"
            if code == "disagreement":
                return SCRIPT["fallback_lpr"], "qual0_disagreement"
            return SCRIPT["qual_step0"], "qual0_repeat"

        elif step == 1:
            if code == "gave_month":
                state.qual_step = 2
                return SCRIPT["qual_contractor_when"], "qual1→qual2"
            if code == "far_date":
                state.phase = "lpr_main"
                state.qual_step = 0
                state.lpr_far_date_pending = True
                return SCRIPT["lpr_far_date"], "qual1_far_date"
            return SCRIPT["qual_step1"], "qual1_repeat"

        elif step == 2:
            if code in ("contractor_now", "contractor_later"):
                state.qual_contractor_later = (code == "contractor_later")
                state.qual_step = 3
                return SCRIPT["qual_contract"], f"qual2→qual3({code})"
            return SCRIPT["qual_contractor_when"], "qual2_repeat"

        elif step == 3:
            if state.qual_platform_pending:
                # Это ответ на вопрос "можно ли напрямую до суммы?"
                state.qual_platform_pending = False
                if code == "platform_direct_yes":
                    return self._qual_after_contract(state, "qual3p")
                # Площадка без прямого договора — уточняем ТЗ и сроки сбора КП
                state.qual_platform_details_pending = True
                return SCRIPT["qual_contract_platform_details"], "qual3p_no→details"
            if code == "direct":
                return self._qual_after_contract(state, "qual3")
            if code == "platform":
                state.qual_platform_pending = True
                return SCRIPT["qual_contract_platform"], "qual3→qual3p"
            return SCRIPT["qual_contract"], "qual3_repeat"

        elif step == 4:
            # Кол-во зданий: один объект → сразу номер; иначе → одновременность
            if _is_single_building(lower):
                state.qual_step = 5
                return SCRIPT["qual_step5"], "qual4→qual5(single)"
            state.qual_step = 7
            return SCRIPT["lpr_fd_simultaneous"], "qual4→qual7(simul)"

        elif step == 7:
            # Одновременно → сразу номер; в разное время → сроки по объектам
            if any(p in lower for p in _SIMULTANEOUS_TERMS):
                state.qual_step = 5
                return SCRIPT["qual_step5"], "qual7→qual5(simul)"
            state.qual_step = 8
            return SCRIPT["lpr_fd_nearest_object"], "qual7→qual8(objects)"

        elif step == 8:
            # Сроки по объектам: «не помню» → примерные; иначе → номер
            if any(p in lower for p in _UNCERTAIN_TERMS):
                state.qual_step = 9
                return SCRIPT["lpr_fd_nearest_approx"], "qual8→qual9(approx)"
            state.qual_step = 5
            return SCRIPT["qual_step5"], "qual8→qual5"

        elif step == 9:
            # Ответили на примерные сроки → номер
            state.qual_step = 5
            return SCRIPT["qual_step5"], "qual9→qual5"

        elif step == 5:
            if code == "says_record":
                return SCRIPT["qual_step5_recording"], "qual5_record"
            if (code in ("gave_phone", "says_phone")
                    or _says_same_number(lower)
                    or any(ch.isdigit() for ch in user_text)):
                return self._qual_close(state)
            if code == "ask_our_number":
                return (
                    SCRIPT["our_phone"] + " И подскажите всё таки, ваш прямой номер?",
                    "ask_our_number",
                )
            return SCRIPT["qual_step5"], "qual5_repeat"

        elif step == 6:
            # Вариант 2: ждали ответ ЛПР на «...свяжемся ближе к срокам...» →
            # финальное прощание
            if state.qual_far_close_pending:
                state.qual_far_close_pending = False
                state.phase = "closed"
                return SCRIPT["qual_close_far_bye"], "qual6_far_bye"
            state.phase = "closed"
            return SCRIPT["qual_step6"], "qual6_closed"

        return SCRIPT["fallback_lpr"], "qual_unknown"

