_SENTENCE_RE = re.compile(r"[^.?!]+[.?!]?")


def _split_questions(text: str) -> tuple[str, str]:
    """Делит реплику на утверждения и вопросы: ``(head, questions)``.

    Нужно, чтобы при повторе темы заменить вопросительную часть перефразировкой,
    сохранив содержательное начало реплики.
    """
    if "?" not in text:
        return text.strip(), ""
    head: list[str] = []
    questions: list[str] = []
    for raw in _SENTENCE_RE.findall(text):
        sentence = raw.strip()
        if not sentence:
            continue
        (questions if sentence.endswith("?") else head).append(sentence)
    return " ".join(head).strip(), " ".join(questions).strip()


def _first_question(text: str) -> str:
    """Первый вопрос из реплики робота (для переспроса при молчании).

    Именно ПЕРВЫЙ: если реплика заканчивалась связкой «Кто отвечает? Инженер
    или энергетик?», переспрашивать надо основной вопрос, а не уточнение.
    """
    _, questions = _split_questions(text)
    if not questions:
        return ""
    for raw in _SENTENCE_RE.findall(questions):
        sentence = raw.strip()
        if sentence.endswith("?"):
            return sentence
    return ""


def _question_topic(question: str) -> str:
    """Тема вопроса ('responsible' / 'plans' / 'phone') или пустая строка."""
    lower = question.lower()
    for topic, markers in _QUESTION_TOPICS:
        if any(m in lower for m in markers):
            return topic
    return ""


