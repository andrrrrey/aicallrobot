"""Нормализация текста перед синтезом речи (TTS).

Главная задача — корректно произносить телефонные номера. TTS-движки читают
"8 800 775 96 31" как единое большое число («восемь миллионов восемьсот тысяч
семьсот семьдесят пять…»), потому что пробелы трактуются как разделители
разрядов. Поэтому телефоноподобные последовательности цифр переводим в
словесную форму по группам:

    "8 800 775 96 31"  →  "восемь восемьсот семьсот семьдесят пять
                            девяносто шесть тридцать один"

Диктовка по группам («восемь — восемьсот — и далее») — это то, как номер
проговаривает живой оператор, поэтому звучит естественно и не искажается.
"""

import re

_ONES = (
    "ноль", "один", "два", "три", "четыре",
    "пять", "шесть", "семь", "восемь", "девять",
)
_TEENS = (
    "десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
    "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать",
)
_TENS = (
    "", "", "двадцать", "тридцать", "сорок", "пятьдесят",
    "шестьдесят", "семьдесят", "восемьдесят", "девяносто",
)
_HUNDREDS = (
    "", "сто", "двести", "триста", "четыреста", "пятьсот",
    "шестьсот", "семьсот", "восемьсот", "девятьсот",
)


def _ru_cardinal(n: int) -> str:
    """Число 0..999 словами (мужской род)."""
    if n == 0:
        return _ONES[0]
    parts: list[str] = []
    h, rem = divmod(n, 100)
    if h:
        parts.append(_HUNDREDS[h])
    if rem >= 20:
        t, o = divmod(rem, 10)
        parts.append(_TENS[t])
        if o:
            parts.append(_ONES[o])
    elif rem >= 10:
        parts.append(_TEENS[rem - 10])
    elif rem > 0:
        parts.append(_ONES[rem])
    return " ".join(parts)


def _speak_group(group: str) -> str:
    """Группа цифр телефона словами.

    До трёх цифр без ведущего нуля читаем как число («800» → «восемьсот»),
    иначе — поразрядно («07» → «ноль семь»), чтобы не терять нули.
    """
    if len(group) <= 3 and not (len(group) > 1 and group[0] == "0"):
        return _ru_cardinal(int(group))
    return " ".join(_ONES[int(c)] for c in group)


# Телефоноподобный токен: цифры, разделённые пробелами/дефисами/скобками/плюсом.
# Начинается и заканчивается цифрой; общее число цифр проверяем отдельно.
_PHONE_RE = re.compile(r"\+?\d[\d\s\-–—()]*\d")

# Минимум цифр, чтобы считать последовательность номером (а не «220 кВ», «5а»).
_MIN_PHONE_DIGITS = 6


def _phone_repl(match: re.Match) -> str:
    token = match.group(0)
    digits = re.sub(r"\D", "", token)
    if len(digits) < _MIN_PHONE_DIGITS:
        return token
    groups = re.findall(r"\d+", token)
    return " ".join(_speak_group(g) for g in groups)


def normalize_for_tts(text: str) -> str:
    """Готовит текст к синтезу: телефонные номера → словесная форма по группам."""
    if not text or not any(ch.isdigit() for ch in text):
        return text
    return _PHONE_RE.sub(_phone_repl, text)
